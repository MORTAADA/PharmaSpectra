import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const app = fs.readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const start = app.indexOf('function applyPhaseCorrection(');
const end = app.indexOf('\nfunction renderDetails(', start);
assert(start >= 0 && end > start, 'phase helper must exist');
const sandbox = {};
vm.runInNewContext(`${app.slice(start, end)}; this.applyPhaseCorrection = applyPhaseCorrection;`, sandbox);
const correct = sandbox.applyPhaseCorrection;
const r = [{x:1,y:1},{x:2,y:0},{x:3,y:1}];
const i = [{x:1,y:0},{x:2,y:1},{x:3,y:0}];
assert.deepEqual(JSON.parse(JSON.stringify(correct(r,i,0,0))), {real:r,imaginary:i});
const ninety = correct(r,i,90,0);
assert.ok(Math.abs(ninety.real[0].y) < 1e-12);
assert.ok(Math.abs(ninety.imaginary[0].y - 1) < 1e-12);
const linear = correct([{x:1,y:1},{x:2,y:1},{x:3,y:1}],[{x:1,y:0},{x:2,y:0},{x:3,y:0}],0,180);
assert.ok(Math.abs(linear.real[0].y) < 1e-12, 'left edge receives -90°');
assert.ok(Math.abs(linear.imaginary[0].y + 1) < 1e-12);
assert.ok(Math.abs(linear.real[1].y - 1) < 1e-12, 'center is the PH1 pivot');
assert.ok(Math.abs(linear.real[2].y) < 1e-12, 'right edge receives +90°');
assert.ok(Math.abs(linear.imaginary[2].y - 1) < 1e-12);
assert.deepEqual(r, [{x:1,y:1},{x:2,y:0},{x:3,y:1}], 'source R data must remain unchanged');
assert.deepEqual(i, [{x:1,y:0},{x:2,y:1},{x:3,y:0}], 'source I data must remain unchanged');
assert.throws(() => correct(r,[{x:1,y:0}],45,0), /même nombre/);
assert.throws(() => correct(r,[{x:1,y:0},{x:3,y:1},{x:3,y:0}],45,0), /non alignés/);
assert.throws(() => correct(r,i,NaN,0), /invalides/);
assert.throws(() => correct(r,i,0,Infinity), /invalides/);
console.log('Phase correction tests passed: PH0, PH1 linear pivot, immutability, alignment, and invalid input.');
